#!/usr/bin/env node
/**
 * Fetches the upstream reference files, verifies them, applies the filters and writes the derived
 * seed files under seed/data plus MANIFEST.json.
 *
 * Rules (docs/increments/03-db-schema.md, section "Package layout"):
 *   - every download is compared against the Content-Length header and fails on a mismatch; two
 *     research downloads returned HTTP 200 with silently truncated bodies that still parsed;
 *   - SHA-256, byte count, Content-Length seen and fetched_at are recorded per source;
 *   - each derived file stays under 3 MB;
 *   - airports with no mwgg timezone get a geo-tz candidate written to airports.tz-review.json,
 *     never straight into the committed overrides: geo-tz boundary data is ODbL, so the reviewed
 *     list is committed as curated data (see seed/data/LICENSES.md).
 *
 * Usage: node scripts/fetch-seed-data.mjs [--out seed/data] [--attempts 3] [--only id,id]
 * Run from packages/db. Needs Node 24 (global fetch) and the geo-tz devDependency.
 */

import { createHash } from 'node:crypto';
import { mkdir, writeFile } from 'node:fs/promises';
import { dirname, join, resolve } from 'node:path';
import { fileURLToPath } from 'node:url';

const packageRoot = resolve(dirname(fileURLToPath(import.meta.url)), '..');
const args = parseArgs(process.argv.slice(2));
const outDir = resolve(packageRoot, args.out ?? 'seed/data');
const attempts = Number(args.attempts ?? 3);
const only = args.only ? new Set(args.only.split(',')) : null;
const MAX_DERIVED_BYTES = 3 * 1024 * 1024;

const VRS_RAW = 'https://raw.githubusercontent.com/vradarserver/standing-data/main';
const MODEL_TYPE_FILES = ['-', ...'ABCDEFGHIJKLMNOPQRSTUVWXYZ'.split('')];

/** @type {Record<string, { url: string; license: string; licenseUrl: string; note?: string }>} */
const SOURCES = {
  ourairports_airports: {
    url: 'https://davidmegginson.github.io/ourairports-data/airports.csv',
    license: 'Unlicense (public domain)',
    licenseUrl: 'https://ourairports.com/data/',
  },
  mwgg_airports: {
    url: 'https://raw.githubusercontent.com/mwgg/Airports/master/airports.json',
    license: 'MIT',
    licenseUrl: 'https://github.com/mwgg/Airports/blob/master/LICENSE',
  },
  vrs_airlines: {
    url: `${VRS_RAW}/airlines/schema-01/airlines.csv`,
    license: 'CC0 1.0',
    licenseUrl: 'https://github.com/vradarserver/standing-data/blob/main/LICENSE',
  },
  optd_airlines: {
    url: 'https://raw.githubusercontent.com/opentraveldata/opentraveldata/master/opentraveldata/optd_airlines.csv',
    license: 'CC BY 4.0',
    licenseUrl: 'https://github.com/opentraveldata/opentraveldata/blob/master/LICENSE',
  },
  coltjd45_aircraft: {
    url: 'https://raw.githubusercontent.com/ColtJD45/icao-aircraft-designator-list/main/icao_aircraft_data.csv',
    license: 'MIT',
    licenseUrl: 'https://github.com/ColtJD45/icao-aircraft-designator-list/blob/main/LICENSE',
    note: 'Frozen 2025-08-19 snapshot; used only to patch wake turbulence category J.',
  },
};
for (const letter of MODEL_TYPE_FILES) {
  SOURCES[`vrs_model_type_${letter === '-' ? 'dash' : letter}`] = {
    url: `${VRS_RAW}/model-type/schema-01/${encodeURIComponent(letter)}.csv`,
    license: 'CC0 1.0',
    licenseUrl: 'https://github.com/vradarserver/standing-data/blob/main/LICENSE',
  };
}

/** @type {Record<string, object>} */
const manifestSources = {};
/** @type {Record<string, { rows: number; bytes: number; sha256: string }>} */
const manifestOutputs = {};
/** @type {string[]} */
const warnings = [];

let raw = {};

async function main() {
  raw = await fetchAll();
  await mkdir(outDir, { recursive: true });

  if (has('ourairports_airports') && has('mwgg_airports')) {
    await buildAirports(raw.ourairports_airports, raw.mwgg_airports);
  }
  if (has('vrs_airlines')) {
    await buildAirlines(raw.vrs_airlines);
  }
  if (has('optd_airlines')) {
    await buildOptdSubset(raw.optd_airlines);
  }
  if (MODEL_TYPE_FILES.every((letter) => has(modelTypeId(letter)))) {
    await buildAircraftTypes(raw);
  }

  const manifest = {
    $comment:
      'Generated by scripts/fetch-seed-data.mjs. Every upstream file was compared against its Content-Length header before use. Outputs are derived, filtered files committed for reproducible seeds; airports.tz-overrides.json is curated by hand from airports.tz-review.json and is not listed under outputs.',
    generated_at: new Date().toISOString(),
    sources: manifestSources,
    outputs: manifestOutputs,
    warnings,
  };
  await writeFile(join(outDir, 'MANIFEST.json'), `${JSON.stringify(manifest, null, 2)}\n`);
  console.log(`wrote ${join(outDir, 'MANIFEST.json')}`);
  if (warnings.length > 0) {
    console.warn(`${warnings.length} warning(s):`);
    for (const warning of warnings) {
      console.warn(`  - ${warning}`);
    }
  }
  const pending = Object.entries(manifestSources).filter(([, s]) => s.status === 'pending');
  if (pending.length > 0) {
    console.error(
      `${pending.length} source(s) could not be fetched: ${pending.map(([id]) => id).join(', ')}`,
    );
    process.exitCode = 2;
  }
}

// ---------------------------------------------------------------------------------------------

function has(id) {
  return raw[id] !== undefined;
}

function modelTypeId(letter) {
  return `vrs_model_type_${letter === '-' ? 'dash' : letter}`;
}

function parseArgs(argv) {
  const out = {};
  for (let i = 0; i < argv.length; i += 1) {
    const arg = argv[i];
    if (arg.startsWith('--')) {
      const key = arg.slice(2);
      const next = argv[i + 1];
      if (next !== undefined && !next.startsWith('--')) {
        out[key] = next;
        i += 1;
      } else {
        out[key] = 'true';
      }
    }
  }
  return out;
}

async function fetchAll() {
  /** @type {Record<string, Uint8Array>} */
  const bodies = {};
  for (const [id, source] of Object.entries(SOURCES)) {
    if (only !== null && !only.has(id)) {
      continue;
    }
    const entry = {
      url: source.url,
      license: source.license,
      license_url: source.licenseUrl,
      ...(source.note ? { note: source.note } : {}),
      status: 'pending',
    };
    manifestSources[id] = entry;
    for (let attempt = 1; attempt <= attempts; attempt += 1) {
      try {
        const result = await download(source.url);
        bodies[id] = result.bytes;
        Object.assign(entry, {
          status: 'fetched',
          sha256: result.sha256,
          bytes: result.bytes.byteLength,
          content_length: result.contentLength,
          last_modified: result.lastModified,
          fetched_at: result.fetchedAt,
        });
        console.log(`fetched ${id}: ${result.bytes.byteLength} bytes (attempt ${attempt})`);
        break;
      } catch (error) {
        const message = error instanceof Error ? error.message : String(error);
        console.warn(`attempt ${attempt}/${attempts} for ${id} failed: ${message}`);
        entry.last_error = message;
        entry.attempted_at = new Date().toISOString();
      }
    }
  }
  return bodies;
}

async function download(url) {
  const fetchedAt = new Date().toISOString();
  // Node's fetch negotiates gzip and decompresses transparently, which makes Content-Length the
  // compressed size. Ask for the identity encoding so the header describes the bytes we count,
  // and refuse a response that is encoded anyway because it cannot be verified.
  const response = await fetch(url, {
    redirect: 'follow',
    headers: { 'accept-encoding': 'identity' },
  });
  if (!response.ok) {
    throw new Error(`HTTP ${response.status} for ${url}`);
  }
  const encoding = response.headers.get('content-encoding');
  if (encoding !== null && encoding !== 'identity') {
    throw new Error(`server ignored accept-encoding: identity (${encoding}) for ${url}`);
  }
  const header = response.headers.get('content-length');
  if (header === null) {
    throw new Error(`no Content-Length header for ${url}; refusing to trust the body`);
  }
  const contentLength = Number(header);
  const bytes = new Uint8Array(await response.arrayBuffer());
  if (bytes.byteLength !== contentLength) {
    throw new Error(
      `truncated download for ${url}: received ${bytes.byteLength} bytes, Content-Length ${contentLength}`,
    );
  }
  return {
    bytes,
    contentLength,
    sha256: sha256Hex(bytes),
    lastModified: response.headers.get('last-modified'),
    fetchedAt,
  };
}

function sha256Hex(bytes) {
  return createHash('sha256').update(bytes).digest('hex');
}

function decode(bytes) {
  let text = new TextDecoder('utf-8').decode(bytes);
  if (text.charCodeAt(0) === 0xfeff) {
    text = text.slice(1);
  }
  return text;
}

/** Minimal RFC 4180 parser: quoted fields, doubled quotes, CRLF or LF. Returns rows as arrays. */
function parseCsv(text, delimiter = ',') {
  const rows = [];
  let row = [];
  let field = '';
  let inQuotes = false;
  for (let i = 0; i < text.length; i += 1) {
    const ch = text[i];
    if (inQuotes) {
      if (ch === '"') {
        if (text[i + 1] === '"') {
          field += '"';
          i += 1;
        } else {
          inQuotes = false;
        }
      } else {
        field += ch;
      }
      continue;
    }
    if (ch === '"') {
      inQuotes = true;
    } else if (ch === delimiter) {
      row.push(field);
      field = '';
    } else if (ch === '\n') {
      row.push(field);
      rows.push(row);
      row = [];
      field = '';
    } else if (ch === '\r') {
      // swallow; LF closes the record
    } else {
      field += ch;
    }
  }
  if (field !== '' || row.length > 0) {
    row.push(field);
    rows.push(row);
  }
  return rows;
}

/** Parses by header name, never by position (the OurAirports column order drifts). */
function parseCsvObjects(text, delimiter = ',') {
  const rows = parseCsv(text, delimiter);
  const header = rows.shift();
  if (header === undefined) {
    throw new Error('empty CSV');
  }
  return rows
    .filter((cells) => cells.length > 1 || (cells.length === 1 && cells[0] !== ''))
    .map((cells) => {
      const obj = {};
      header.forEach((name, index) => {
        obj[name] = cells[index] ?? '';
      });
      return obj;
    });
}

function csvEscape(value) {
  const s = value === null || value === undefined ? '' : String(value);
  return /[",\r\n]/.test(s) ? `"${s.replaceAll('"', '""')}"` : s;
}

function toCsv(header, rows) {
  const lines = [header.join(',')];
  for (const row of rows) {
    lines.push(header.map((key) => csvEscape(row[key])).join(','));
  }
  return `${lines.join('\n')}\n`;
}

async function writeDerived(name, content, rows) {
  const bytes = new TextEncoder().encode(content);
  if (bytes.byteLength > MAX_DERIVED_BYTES) {
    throw new Error(`${name} is ${bytes.byteLength} bytes, over the 3 MB limit`);
  }
  await writeFile(join(outDir, name), bytes);
  manifestOutputs[name] = { rows, bytes: bytes.byteLength, sha256: sha256Hex(bytes) };
  console.log(`wrote ${name}: ${rows} rows, ${bytes.byteLength} bytes`);
}

// ---------------------------------------------------------------------------------------------
// Airports

const AIRPORT_COLUMNS = [
  'id',
  'ident',
  'type',
  'name',
  'latitude_deg',
  'longitude_deg',
  'elevation_ft',
  'continent',
  'iso_country',
  'iso_region',
  'municipality',
  'scheduled_service',
  'icao_code',
  'iata_code',
  'gps_code',
  'local_code',
  'tz_mwgg',
];

async function buildAirports(ourairportsBytes, mwggBytes) {
  const all = parseCsvObjects(decode(ourairportsBytes));
  const mwgg = JSON.parse(decode(mwggBytes));
  const byIcao = new Map();
  const byIata = new Map();
  for (const entry of Object.values(mwgg)) {
    if (entry.icao) {
      byIcao.set(entry.icao, entry.tz);
    }
    if (entry.iata && !byIata.has(entry.iata)) {
      byIata.set(entry.iata, entry.tz);
    }
  }
  const filtered = all.filter(
    (row) =>
      row.scheduled_service === 'yes' ||
      row.type === 'large_airport' ||
      row.type === 'medium_airport',
  );
  const missing = [];
  const rows = filtered.map((row) => {
    const tz =
      byIcao.get(row.icao_code) ??
      byIcao.get(row.ident) ??
      byIcao.get(row.gps_code) ??
      byIata.get(row.iata_code) ??
      '';
    const out = {};
    for (const key of AIRPORT_COLUMNS) {
      out[key] = key === 'tz_mwgg' ? tz : row[key];
    }
    if (tz === '') {
      missing.push(row);
    }
    return out;
  });
  rows.sort((a, b) => (a.ident < b.ident ? -1 : a.ident > b.ident ? 1 : 0));
  await writeDerived('airports.filtered.csv', toCsv(AIRPORT_COLUMNS, rows), rows.length);

  const seenTypes = [...new Set(all.map((row) => row.type))].sort();
  manifestSources.ourairports_airports.observed_types = seenTypes;
  manifestSources.ourairports_airports.rows_total = all.length;
  manifestSources.ourairports_airports.rows_filtered = rows.length;
  manifestSources.mwgg_airports.entries = Object.keys(mwgg).length;
  manifestSources.mwgg_airports.tz_matched = rows.length - missing.length;
  manifestSources.mwgg_airports.tz_missing = missing.length;

  // geo-tz candidates for review. Never written to the overrides file by this script. The
  // `all` entry point returns unmerged canonical zones; the default `find-1970` build merges
  // zones with identical rules since 1970 and reports Papua as Asia/Tokyo.
  const { find } = await import('geo-tz/all');
  const review = missing.map((row) => {
    const lat = Number(row.latitude_deg);
    const lon = Number(row.longitude_deg);
    const candidates = Number.isFinite(lat) && Number.isFinite(lon) ? find(lat, lon) : [];
    return {
      icao: row.icao_code || row.ident,
      ident: row.ident,
      name: row.name,
      type: row.type,
      iso_country: row.iso_country,
      iso_region: row.iso_region,
      latitude_deg: lat,
      longitude_deg: lon,
      candidate: candidates[0] ?? null,
      candidates,
    };
  });
  const reviewDoc = {
    $comment:
      'REVIEW FILE. geo-tz (ODbL boundary data) candidates for airports with no mwgg/Airports timezone. A human or the orchestrator checks each candidate against the airport country and promotes accepted entries into airports.tz-overrides.json. The loader never reads this file.',
    generated_at: new Date().toISOString(),
    count: review.length,
    entries: review,
  };
  await writeDerived(
    'airports.tz-review.json',
    `${JSON.stringify(reviewDoc, null, 2)}\n`,
    review.length,
  );
}

// ---------------------------------------------------------------------------------------------
// Airlines

async function buildAirlines(bytes) {
  const rows = parseCsvObjects(decode(bytes));
  const header = [
    'Code',
    'Name',
    'ICAO',
    'IATA',
    'PositioningFlightPattern',
    'CharterFlightPattern',
  ];
  for (const key of header) {
    if (!(key in rows[0])) {
      throw new Error(`vrs airlines.csv is missing column ${key}`);
    }
  }
  await writeDerived('airlines.csv', toCsv(header, rows), rows.length);
  manifestSources.vrs_airlines.rows_with_icao = rows.filter((r) => r.ICAO !== '').length;
}

async function buildOptdSubset(bytes) {
  const rows = parseCsvObjects(decode(bytes), '^');
  const header = [
    'pk',
    'validity_from',
    'validity_to',
    '3char_code',
    '2char_code',
    'name',
    'alliance_code',
    'alliance_status',
    'type',
  ];
  const subset = rows.filter((row) => row.env_id === '' && row['3char_code'] !== '');
  await writeDerived('optd_airlines.subset.csv', toCsv(header, subset), subset.length);
  manifestSources.optd_airlines.rows_total = rows.length;
  manifestSources.optd_airlines.alliance_values_seen = [
    ...new Set(subset.map((r) => r.alliance_code).filter((v) => v !== '')),
  ].sort();
}

