// Aircraft types

const AIRCRAFT_TYPE_COLUMNS = [
  'icao',
  'manufacturer',
  'model',
  'engines',
  'engine_type_code',
  'engine_placement_code',
  'species_code',
  'wake_turbulence',
  'wake_source',
  'is_active',
];

async function buildAircraftTypes(bodies) {
  const byIcao = new Map();
  let total = 0;
  let dropped = 0;
  for (const letter of MODEL_TYPE_FILES) {
    const rows = parseCsvObjects(decode(bodies[modelTypeId(letter)]));
    for (const row of rows) {
      total += 1;
      const icao = row.ICAO.trim();
      if (icao === '' || icao.startsWith('-')) {
        dropped += 1;
        continue;
      }
      const active = row.IsActive === '1';
      const existing = byIcao.get(icao);
      // Prefer IsActive=1; among equals keep the first occurrence.
      if (existing === undefined || (active && !existing.active)) {
        byIcao.set(icao, { row, active });
      }
    }
  }
  // Distinct designators, not rows: ColtJD45 lists A388 twice (one row per model variant).
  const patchedJ = new Set();
  let coltRows = 0;
  if (bodies.coltjd45_aircraft !== undefined) {
    const colt = parseCsvObjects(decode(bodies.coltjd45_aircraft));
    coltRows = colt.length;
    for (const row of colt) {
      if (row.wtc === 'J') {
        const entry = byIcao.get(row.type_designator);
        if (entry !== undefined) {
          entry.wake = 'J';
          entry.wakeSource = 'coltjd45';
          patchedJ.add(row.type_designator);
        } else {
          warnings.push(
            `ColtJD45 lists ${row.type_designator} as J but VRS has no such designator`,
          );
        }
      }
    }
  } else {
    warnings.push('ColtJD45 not fetched; wake turbulence J patch skipped');
  }
  const rows = [...byIcao.entries()]
    .sort(([a], [b]) => (a < b ? -1 : a > b ? 1 : 0))
    .map(([icao, entry]) => ({
      icao,
      manufacturer: entry.row.Manufacturer,
      model: entry.row.Model,
      engines: entry.row.Engines,
      engine_type_code: entry.row.EngineTypeCode,
      engine_placement_code: entry.row.EnginePlacementCode,
      species_code: entry.row.SpeciesCode,
      wake_turbulence: entry.wake ?? entry.row.WakeTurbulenceCode,
      wake_source: entry.wakeSource ?? (entry.row.WakeTurbulenceCode === '' ? '' : 'vrs'),
      is_active: entry.active ? '1' : '0',
    }));
  await writeDerived('aircraft-types.csv', toCsv(AIRCRAFT_TYPE_COLUMNS, rows), rows.length);
  manifestOutputs['aircraft-types.csv'].vrs_rows_total = total;
  manifestOutputs['aircraft-types.csv'].vrs_rows_dropped_fake_designator = dropped;
  manifestOutputs['aircraft-types.csv'].wake_turbulence_values_seen = [
    ...new Set(rows.map((r) => r.wake_turbulence)),
  ].sort();
  manifestOutputs['aircraft-types.csv'].coltjd45_rows = coltRows;
  manifestOutputs['aircraft-types.csv'].patched_j = patchedJ.size;
  manifestOutputs['aircraft-types.csv'].patched_j_designators = [...patchedJ].sort();
}

await main();
