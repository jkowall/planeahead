#!/usr/bin/env node
/**
 * Generates `apps/api/src/generated/migration-hash.ts` from
 * `packages/db/migrations/meta/_journal.json`.
 *
 * Why a generated constant instead of an import: `GET /health` reports the SHA-256 of the
 * migration journal so a deploy can prove which schema the Worker was built against, but
 * `packages/db/src/migrate.ts` is Node only (it reads the migrations folder with `node:fs`) and
 * cannot be imported into a Worker. The hash is therefore computed at build time by this script
 * and compiled into the bundle. The algorithm is byte-for-byte the same as `migrationHash()` in
 * `@planeahead/db/migrate`, so the value the Worker reports and the value the migrator computes
 * against the same checkout are identical.
 *
 * Run by the api `typecheck`, `test` and `dev` scripts. The output is committed. Pass `--check`
 * to fail instead of writing when the committed file is stale; CI uses that.
 *
 * Deliberately dependency free so it can run before install.
 */

import { createHash } from 'node:crypto';
import { mkdirSync, readFileSync, writeFileSync } from 'node:fs';
import { dirname, join } from 'node:path';
import { fileURLToPath } from 'node:url';

const repoRoot = dirname(dirname(fileURLToPath(import.meta.url)));
const journalPath = join(repoRoot, 'packages', 'db', 'migrations', 'meta', '_journal.json');
const outputPath = join(repoRoot, 'apps', 'api', 'src', 'generated', 'migration-hash.ts');
const checkOnly = process.argv.includes('--check');

const journalBytes = readFileSync(journalPath);
const hash = createHash('sha256').update(journalBytes).digest('hex');

/** @type {{ entries?: { tag: string }[] }} */
const journal = JSON.parse(journalBytes.toString('utf8'));
const entries = journal.entries ?? [];
const latest = entries.length > 0 ? entries[entries.length - 1].tag : '';

const contents = `/**
 * Generated by scripts/gen-migration-hash.mjs from packages/db/migrations/meta/_journal.json.
 * Do not edit by hand: \`pnpm --filter @planeahead/api run gen:migration-hash\` rewrites it, and
 * the api typecheck, test and dev scripts run that first.
 *
 * MIGRATION_HASH is the SHA-256 of the journal file's bytes, the same value
 * \`migrationHash()\` in @planeahead/db/migrate computes. GET /health reports it so a deploy can
 * be matched to the schema it was built against without a database round trip.
 */

export const MIGRATION_HASH = '${hash}';

/** Number of migrations in the journal at build time. */
export const MIGRATION_COUNT = ${entries.length};

/** Tag of the newest migration in the journal at build time. */
export const LATEST_MIGRATION = '${latest}';
`;

let existing = null;
try {
  existing = readFileSync(outputPath, 'utf8');
} catch {
  existing = null;
}

if (existing === contents) {
  console.log(
    `gen-migration-hash: up to date (${hash.slice(0, 12)}..., ${entries.length} migrations)`,
  );
  process.exit(0);
}

if (checkOnly) {
  console.error('gen-migration-hash: FAIL');
  console.error(`  - ${outputPath} is stale`);
  console.error(
    '  - run "pnpm --filter @planeahead/api run gen:migration-hash" and commit the result',
  );
  process.exit(1);
}

mkdirSync(dirname(outputPath), { recursive: true });
writeFileSync(outputPath, contents);
console.log(`gen-migration-hash: wrote ${hash.slice(0, 12)}... (${entries.length} migrations)`);
